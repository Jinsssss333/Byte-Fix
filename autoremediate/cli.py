"""CLI interface for Auto-Remediate built with Typer and Rich."""
import os
import sys
import json
import shutil
import subprocess
from pathlib import Path
from typing import Any

import typer
from rich.console import Console
from rich.panel import Panel
from rich.table import Table
from rich.syntax import Syntax
from rich.text import Text

from autoremediate.hook import load_failure, list_failures
from autoremediate.agent import run_agent, AgentResult
from autoremediate.verify import verify, apply_patch_to_repo

app = typer.Typer(help="Auto-Remediate: Automated Celery crash debugging and verification.")
console = Console()


def _get_recording_path(failure_id: str) -> Path:
    rec_dir = Path(os.getenv("RECORDINGS_DIR", "recordings")).resolve()
    return rec_dir / f"run_{failure_id}.json"


def _format_pr_body(
    task_name: str,
    root_cause: str,
    evidence: list[str],
    patched_files: list[str],
    exception_type: str,
    confidence: str,
) -> str:
    ev_lines = "\n".join(f"- {e}" for e in evidence) if evidence else "- (none)"
    files_lines = "\n".join(f"- `{f}`" for f in patched_files)
    return (
        f"# fix: {task_name} (auto-remediate)\n\n"
        f"## Root Cause\n{root_cause}\n\n"
        f"## Evidence\n{ev_lines}\n\n"
        f"## Files Changed\n{files_lines}\n\n"
        f"## How it was verified\n"
        f"- Failing reproducer test failed with `{exception_type}` before patch\n"
        f"- Reproducer test passed cleanly after patch applied\n"
        f"- Full test suite passed with zero regressions\n\n"
        f"**Confidence**: {confidence}\n\n"
        "Generated by Auto-Remediate. Review before merging.\n"
    )


@app.command(name="list")
def list_cmd():
    """List all captured task failures."""
    failures = list_failures()
    if not failures:
        console.print("[yellow]No captured failures found.[/yellow]")
        return

    table = Table(title="Captured Task Failures", show_header=True, header_style="bold cyan")
    table.add_column("ID", style="bold", width=4)
    table.add_column("Time", width=19)
    table.add_column("Task", style="green", no_wrap=True)
    table.add_column("Exception", style="red")

    for f in failures:
        f_id = str(f.get("id", ""))
        ts = str(f.get("timestamp", ""))[:19].replace("T", " ")
        task = str(f.get("task_name", ""))
        exc = f"{f.get('exception_type', '')}: {f.get('exception_message', '')}"
        table.add_row(f_id, ts, task, exc)

    console.print(table)


@app.command(name="serve-webhook")
def serve_webhook(
    host: str = typer.Option("0.0.0.0", "--host", help="Host interface to bind on"),
    port: int = typer.Option(8000, "--port", help="Port to listen for Sentry webhooks"),
):
    """Start an HTTP server to ingest incoming Sentry crash webhooks."""
    from http.server import HTTPServer
    from autoremediate.sentry import create_sentry_webhook_handler

    def on_event(fid: str):
        console.print(f"[bold green]Ingested Sentry failure #{fid} into failures/{fid}.json[/bold green]")
        console.print(f"Run [cyan]autoremediate fix {fid}[/cyan] to diagnose and verify.")

    handler_cls = create_sentry_webhook_handler(on_event_callback=on_event)
    server = HTTPServer((host, port), handler_cls)
    console.print(f"[bold cyan]Auto-Remediate Sentry webhook server running on http://{host}:{port}/webhook/sentry[/bold cyan]")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        console.print("\n[yellow]Webhook server stopped.[/yellow]")
        server.server_close()


@app.command()
def fix(
    failure_id: str = typer.Argument(..., help="The failure ID to remediate"),
    replay: bool = typer.Option(False, "--replay", help="Replay from saved recording without calling LLM"),
    apply: bool = typer.Option(False, "--apply", help="Apply patch to repo if verified"),
    pr: bool = typer.Option(False, "--pr", help="Apply patch and create a git branch and pull request"),
    telegram: bool = typer.Option(False, "--telegram", help="Send approval request with inline buttons to Telegram"),
):
    """Diagnose, patch, and verify a captured task failure."""
    repo_root = Path.cwd().resolve()
    tests_dir = os.getenv("TARGET_TESTS", "demo_app/tests")

    # Load failure
    try:
        failure = load_failure(failure_id)
    except FileNotFoundError:
        console.print(f"[bold red]Error: Failure ID '{failure_id}' not found.[/bold red]")
        raise typer.Exit(code=2)
    except Exception as exc:
        console.print(f"[bold red]Error loading failure '{failure_id}': {exc}[/bold red]")
        raise typer.Exit(code=2)

    # 1. Failure panel
    task_name = failure.get("task_name", "unknown")
    exc_type = failure.get("exception_type", "Exception")
    exc_msg = failure.get("exception_message", "")
    frames = failure.get("frames", [])

    failure_text = Text()
    failure_text.append(f"Task: {task_name}\n", style="bold white")
    failure_text.append(f"Exception: {exc_type}: {exc_msg}\n\n", style="bold red")

    if frames:
        last_frame = frames[-1]
        failure_text.append(f"Frame: {last_frame.get('file', '')}:{last_frame.get('line', '')} in {last_frame.get('function', '')}\n", style="cyan")
        failure_text.append(f"Code:  {last_frame.get('code', '')}\n\n", style="yellow")
        failure_text.append("Locals:\n", style="bold")
        for k, v in last_frame.get("locals", {}).items():
            failure_text.append(f"  {k} = ")
            if v == "None":
                failure_text.append("None\n", style="bold red on black")
            else:
                failure_text.append(f"{v}\n", style="white")

    console.print(Panel(failure_text, title=f"[bold]Failure #{failure_id}[/bold]", border_style="red"))

    # 2. Agent trace & final determination
    final: dict[str, Any] = {}
    recording_file = _get_recording_path(failure_id)

    if replay:
        if not recording_file.exists():
            console.print(f"[bold red]Replay error: No recording found at {recording_file}[/bold red]")
            raise typer.Exit(code=1)
        try:
            recording_data = json.loads(recording_file.read_text(encoding="utf-8"))
            final = recording_data["final"]
            trace = recording_data.get("trace", [])
            console.print(f"[cyan]Loaded replay from {recording_file}[/cyan]")
            for step in trace:
                console.print(f"  [bold]Step {step.get('step')}[/bold] [{step.get('type')}]: {step.get('detail')} ({step.get('model')})")

            if final.get("kind") == "give_up":
                reason = final.get("reason", "")
                evidence = final.get("evidence", [])
                ev_text = "\n".join(f"- {e}" for e in evidence)
                content = f"[bold]Reason:[/bold] {reason}\n\n[bold]Evidence:[/bold]\n{ev_text}"
                console.print(Panel(content, title="[bold yellow]COULD NOT REPRODUCE[/bold yellow]", border_style="yellow"))
                raise typer.Exit(code=1)
        except typer.Exit:
            raise
        except Exception as exc:
            console.print(f"[bold red]Error reading recording: {exc}[/bold red]")
            raise typer.Exit(code=1)
    else:
        def on_step(entry: dict):
            console.print(f"  [bold]Step {entry.get('step')}[/bold] [{entry.get('type')}]: {entry.get('detail')} ({entry.get('model')})")

        console.print("[bold cyan]Agent trace:[/bold cyan]")
        try:
            agent_result = run_agent(failure, repo_root=repo_root, on_step=on_step)
        except RuntimeError as exc:
            console.print(f"[bold red]LLM Error: {exc}[/bold red]")
            if recording_file.exists():
                console.print(f"[yellow]Suggestion: run with --replay to use existing recording {recording_file.name}[/yellow]")
            raise typer.Exit(code=1)

        if agent_result.kind == "error":
            console.print(Panel(f"[bold red]AGENT_ERROR[/bold red]: {agent_result.payload.get('reason', '')}", border_style="red"))
            raise typer.Exit(code=1)

        if agent_result.kind == "give_up":
            reason = agent_result.payload.get("reason", "")
            evidence = agent_result.payload.get("evidence", [])
            ev_text = "\n".join(f"- {e}" for e in evidence)
            content = f"[bold]Reason:[/bold] {reason}\n\n[bold]Evidence:[/bold]\n{ev_text}"
            console.print(Panel(content, title="[bold yellow]COULD NOT REPRODUCE[/bold yellow]", border_style="yellow"))
            raise typer.Exit(code=1)

        final = agent_result.payload

        # Save recording on successful final
        try:
            recording_file.parent.mkdir(parents=True, exist_ok=True)
            recording_file.write_text(
                json.dumps(
                    {
                        "failure_id": failure_id,
                        "final": final,
                        "trace": agent_result.trace,
                    },
                    indent=2,
                ),
                encoding="utf-8",
            )
        except Exception as exc:
            console.print(f"[yellow]Warning: Could not save recording: {exc}[/yellow]")

    # Run verification
    verify_result = verify(failure, final, repo_root=repo_root, tests_dir=tests_dir)

    # 3. Reproducer section
    reproducer_code = final.get("reproducer_test", "")
    console.print(Panel(Syntax(reproducer_code, "python", theme="monokai", line_numbers=True), title="[bold]Reproducer Test[/bold]", border_style="blue"))
    stage1 = next((s for s in verify_result.stages if s.name == "reproducer_fails_before"), None)
    if stage1 and stage1.passed:
        console.print("[bold red]FAILED before patch (expected exception matched)[/bold red]")
    else:
        console.print("[bold yellow]Stage 1 did not fail as expected[/bold yellow]")

    # 4. Patch section
    diff_text = verify_result.diff
    if diff_text:
        console.print(Panel(Syntax(diff_text, "diff", theme="monokai"), title="[bold]Proposed Patch[/bold]", border_style="blue"))
    stage3 = next((s for s in verify_result.stages if s.name == "reproducer_passes_after"), None)
    if stage3 and stage3.passed:
        console.print("[bold green]PASSED after patch[/bold green]")

    # 5. Regression check section
    stage4 = next((s for s in verify_result.stages if s.name == "suite_passes"), None)
    if stage4 and stage4.passed:
        console.print("[bold green]Existing tests pass (no regressions)[/bold green]")
    elif stage4:
        console.print("[bold red]Existing tests failed with regression[/bold red]")

    # 6. Result banner
    if verify_result.status == "VERIFIED":
        root_cause = final.get("root_cause", "")
        evidence = final.get("evidence", [])
        confidence = final.get("confidence", "high")
        ev_fmt = "\n".join(f"- {e}" for e in evidence)
        banner_content = (
            f"[bold green]VERIFIED[/bold green] (confidence: {confidence})\n\n"
            f"[bold]Root Cause:[/bold] {root_cause}\n"
            f"[bold]Evidence:[/bold]\n{ev_fmt}"
        )
        console.print(Panel(banner_content, border_style="green"))

        # 7. PR description
        patched_paths = list(final.get("patched_files", {}).keys())
        pr_markdown = _format_pr_body(
            task_name=task_name,
            root_cause=root_cause,
            evidence=evidence,
            patched_files=patched_paths,
            exception_type=exc_type,
            confidence=confidence,
        )
        console.print(Panel(pr_markdown, title="[bold]Pull Request Description[/bold]", border_style="magenta"))

        # Apply patch if requested
        if apply or pr:
            modified = apply_patch_to_repo(final, repo_root=repo_root)
            console.print(f"[bold green]Applied patch to {len(modified)} file(s): {', '.join(modified)}[/bold green]")

        # Handle --pr flow
        if pr:
            branch_name = f"autoremediate/fix-{failure_id}"
            repro_dest = repo_root / tests_dir / f"test_repro_{failure_id}.py"
            repro_dest.parent.mkdir(parents=True, exist_ok=True)
            repro_dest.write_text(reproducer_code, encoding="utf-8")

            git_success = False
            try:
                subprocess.run(["git", "checkout", "-b", branch_name], cwd=repo_root, check=True, capture_output=True, text=True)
                git_add_files = modified + [str(repro_dest.relative_to(repo_root))]
                subprocess.run(["git", "add"] + git_add_files, cwd=repo_root, check=True, capture_output=True, text=True)
                subprocess.run(["git", "commit", "-m", f"fix: {task_name} (auto-remediate)"], cwd=repo_root, check=True, capture_output=True, text=True)
                git_success = True
            except Exception as git_exc:
                console.print(f"[yellow]Git operations encountered an issue: {git_exc}[/yellow]")
                console.print("Manual git steps:")
                console.print(f"  git checkout -b {branch_name}")
                console.print(f"  git add {' '.join(modified)} {repro_dest.relative_to(repo_root)}")
                console.print(f"  git commit -m 'fix: {task_name} (auto-remediate)'")

            if git_success:
                try:
                    gh_proc = subprocess.run(
                        ["gh", "pr", "create", "--title", f"fix: {task_name} (auto-remediate)", "--body", pr_markdown],
                        cwd=repo_root,
                        capture_output=True,
                        text=True,
                        check=False,
                    )
                    if gh_proc.returncode == 0:
                        console.print(f"[bold green]Pull request created successfully via gh![/bold green]\n{gh_proc.stdout.strip()}")
                    else:
                        console.print(f"[yellow]gh pr create failed ({gh_proc.stderr.strip() or 'non-zero exit'}). Manual steps:[/yellow]")
                        console.print(f"  git push -u origin {branch_name}")
                        console.print(f"  gh pr create --title 'fix: {task_name} (auto-remediate)'")
                except FileNotFoundError:
                    console.print("[yellow]gh CLI not found on PATH. Manual steps to create PR:[/yellow]")
                    console.print(f"  git push -u origin {branch_name}")
                    console.print(f"  gh pr create --title 'fix: {task_name} (auto-remediate)'")
                except Exception as gh_exc:
                    console.print(f"[yellow]gh error: {gh_exc}. Manual steps:[/yellow]")
                    console.print(f"  git push -u origin {branch_name}")
                    console.print(f"  gh pr create --title 'fix: {task_name} (auto-remediate)'")

        # Dispatch to Telegram if requested and wait inline for human decision
        if telegram:
            from autoremediate.telegram import send_and_wait_for_approval
            console.print("\n[bold cyan]📱 Dispatching approval card to Telegram...[/bold cyan]")
            console.print("[dim]Tap 'Approve' or 'Reject' on your phone (Press Ctrl+C to skip wait)[/dim]")
            try:
                approved = send_and_wait_for_approval(
                    failure=failure,
                    final=final,
                    diff=verify_result.diff,
                    repo_root=repo_root,
                    timeout=180,
                )
                if approved:
                    console.print("[bold green]✅ Approved via Telegram! Applied patch to codebase.[/bold green]")
                else:
                    console.print("[yellow]Telegram approval was rejected, timed out, or not configured.[/yellow]")
            except KeyboardInterrupt:
                console.print("\n[yellow]Skipped waiting for Telegram response.[/yellow]")

        raise typer.Exit(code=0)
    else:
        # Non-verified result banner
        banner_content = f"[bold red]{verify_result.status}[/bold red]: {verify_result.reason}"
        console.print(Panel(banner_content, border_style="red"))
        raise typer.Exit(code=1)


@app.command(name="telegram-notify")
def telegram_notify(
    failure_id: str = typer.Argument(..., help="The failure ID to send for Telegram approval"),
):
    """Send an approval request to Telegram for an existing verified failure."""
    from autoremediate.telegram import send_approval_request
    try:
        failure = load_failure(failure_id)
    except Exception as exc:
        console.print(f"[bold red]Error loading failure: {exc}[/bold red]")
        raise typer.Exit(code=2)

    rec_dir = Path(os.getenv("RECORDINGS_DIR", "recordings"))
    rec_file = rec_dir / f"run_{failure_id}.json"
    if not rec_file.exists():
        console.print(f"[bold red]Error: No recording found at {rec_file}. Run 'autoremediate fix {failure_id}' first.[/bold red]")
        raise typer.Exit(code=1)

    rec_data = json.loads(rec_file.read_text(encoding="utf-8"))
    final = rec_data.get("final", {})
    diff = rec_data.get("diff", "")
    ok = send_approval_request(failure=failure, final=final, diff=diff)
    if ok:
        console.print(f"[bold green]Approval request for failure #{failure_id} sent to Telegram![/bold green]")
    else:
        console.print("[bold red]Failed to send Telegram request. Check TELEGRAM_BOT_TOKEN and TELEGRAM_CHAT_ID.[/bold red]")
        raise typer.Exit(code=1)


@app.command(name="telegram-listen")
def telegram_listen(
    timeout: int = typer.Option(20, "--timeout", help="Long-polling timeout in seconds"),
):
    """Listen for Telegram approval/rejection button clicks and apply approved patches."""
    from autoremediate.telegram import listen_for_approvals
    repo_root = Path.cwd().resolve()
    console.print("[bold cyan]Listening for Telegram approvals... (Press Ctrl+C to stop)[/bold cyan]")
    try:
        listen_for_approvals(repo_root=repo_root, poll_timeout=timeout)
    except KeyboardInterrupt:
        console.print("\n[yellow]Telegram listener stopped.[/yellow]")


if __name__ == "__main__":
    app()
